package capgemini;

public class Calculator {

    public int add(int a, int b) {
        return a + b;
    }

    public int sub(int a, int b) {
        return a - b;
    }

    public boolean even(int n) {
        return n % 2 == 0;
    }

    public int divide(int a, int b) {
        return a / b;
    }

    public String getName(String name) {
        return name;
    }
}
